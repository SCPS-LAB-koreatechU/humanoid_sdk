# source ~/humanoid_sdk/env.sh        -- on the robot computer and on the PC alike
#
# ROS 2 Humble (or TogetheROS on the RDK X5), the description workspace if one
# is built separately, this workspace, and the ROS_DOMAIN_ID both machines must
# share. Override with BHL_ROS_DOMAIN_ID (the RDK X5 pairing in
# Berkeley-humanoid-lite/onboard_x5 uses 77; DexHand MoveIt sits on 0).
_ws="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [ -f /opt/ros/humble/setup.bash ]; then
  source /opt/ros/humble/setup.bash
elif [ -f /opt/tros/humble/setup.bash ]; then
  source /opt/tros/humble/setup.bash
else
  echo "env.sh: no ROS 2 Humble found (/opt/ros/humble or /opt/tros/humble)" >&2
fi
# URDF + meshes (berkeley_humanoid_lite_description): either a separate
# Berkeley-Humanoid-Lite checkout built at BHL_DESCRIPTION_WS, or imported into
# this workspace with humanoid.repos (then this line finds nothing and is a no-op).
BHL_DESCRIPTION_WS="${BHL_DESCRIPTION_WS:-$HOME/Berkeley-Humanoid-Lite/ros2_ws}"
[ -f "$BHL_DESCRIPTION_WS/install/setup.bash" ] && source "$BHL_DESCRIPTION_WS/install/setup.bash"
[ -f "$_ws/ros2_ws/install/setup.bash" ] && source "$_ws/ros2_ws/install/setup.bash"
export ROS_DOMAIN_ID="${BHL_ROS_DOMAIN_ID:-92}"
export ROS_LOCALHOST_ONLY=0
# Pin Fast DDS to one address (the wired link between robot and PC) plus
# loopback and shared memory. With Wi-Fi up as well, DDS also sends over the
# slow Wi-Fi path and a blocked publish stalls the control loop (seen
# 2026-10-20 on the RDK X5). Set the address with BHL_DDS_IP or in
# ~/.config/bhl_arm_sdk/dds_ip, on BOTH machines (pinning only one side is not
# enough); empty = Fast DDS default (every interface).
_dds_ip="${BHL_DDS_IP-$(cat "$HOME/.config/bhl_arm_sdk/dds_ip" 2>/dev/null || true)}"
if [ -n "$_dds_ip" ] && ! ip -4 -o addr 2>/dev/null | grep -qw "inet $_dds_ip"; then
  # e.g. cable unplugged: pinning to a missing address would leave DDS on
  # loopback only and the other machine would see nothing.
  echo "env.sh: $_dds_ip not on this machine -- Fast DDS uses all interfaces" >&2
  _dds_ip=""
fi
if [ -n "$_dds_ip" ]; then
  _xml="$HOME/.config/bhl_arm_sdk/fastdds_$_dds_ip.xml"
  mkdir -p "$(dirname "$_xml")"
  cat > "$_xml" <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by humanoid_sdk/env.sh: Fast DDS only on $_dds_ip (+ loopback, shm) -->
<profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <transport_descriptors>
    <transport_descriptor>
      <transport_id>bhl_udp</transport_id>
      <type>UDPv4</type>
      <interfaceWhiteList>
        <address>$_dds_ip</address>
        <address>127.0.0.1</address>
      </interfaceWhiteList>
    </transport_descriptor>
    <transport_descriptor>
      <transport_id>bhl_shm</transport_id>
      <type>SHM</type>
    </transport_descriptor>
  </transport_descriptors>
  <participant profile_name="bhl_pinned" is_default_profile="true">
    <rtps>
      <userTransports>
        <transport_id>bhl_udp</transport_id>
        <transport_id>bhl_shm</transport_id>
      </userTransports>
      <useBuiltinTransports>false</useBuiltinTransports>
    </rtps>
  </participant>
</profiles>
XML
  export FASTRTPS_DEFAULT_PROFILES_FILE="$_xml"
  unset _xml
fi
unset _ws _dds_ip
